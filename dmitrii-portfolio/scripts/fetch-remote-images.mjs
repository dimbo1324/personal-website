#!/usr/bin/env node
/**
 * Downloads the Unsplash images listed in js/data/remoteImages.js into
 * assets/images/remote/<id>-<width>.webp so the site no longer depends on
 * images.unsplash.com (faster, works offline, stricter CSP).
 *
 * Writes:
 *   assets/images/remote/manifest.json   — used by the build to rewrite URLs in index.html
 *   js/data/generated/localImages.js     — tells the gallery which images are local
 *
 * Usage:  npm run images:fetch     (needs internet; re-run is incremental)
 */
import { mkdir, writeFile, stat } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join, relative } from "node:path";
import { REMOTE_IMAGES, REMOTE_WIDTHS } from "../js/data/remoteImages.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "assets", "images", "remote");
const GENERATED = join(ROOT, "js", "data", "generated", "localImages.js");

const url = (photoId, width) => `https://images.unsplash.com/${photoId}?auto=format&fit=crop&w=${width}&q=75&fm=webp`;
const exists = (path) =>
  stat(path).then(
    () => true,
    () => false,
  );

async function download(source, target) {
  if (await exists(target)) return "cached";
  const response = await fetch(source, { headers: { Accept: "image/webp" } });
  if (!response.ok) throw new Error(`${response.status} ${response.statusText}`);
  await writeFile(target, Buffer.from(await response.arrayBuffer()));
  return "downloaded";
}

await mkdir(OUT, { recursive: true });
const manifest = { files: {} };
const local = [];

for (const [id, photoId] of Object.entries(REMOTE_IMAGES)) {
  try {
    for (const width of REMOTE_WIDTHS) {
      const target = join(OUT, `${id}-${width}.webp`);
      const result = await download(url(photoId, width), target);
      manifest.files[`${photoId}@${width}`] = relative(ROOT, target).split("\\").join("/");
      console.log(`  ${result.padEnd(10)} ${id}-${width}.webp`);
    }
    local.push(id);
  } catch (error) {
    console.warn(`  ! ${id}: ${error.message} — it will keep loading from Unsplash`);
  }
}

await writeFile(join(OUT, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
await writeFile(
  GENERATED,
  [
    "// Generated by `npm run images:fetch` (scripts/fetch-remote-images.mjs) — do not edit by hand.",
    "// Lists the remote (Unsplash) images that have been downloaded to assets/images/remote/,",
    "// so the site serves them locally instead of from images.unsplash.com.",
    `export const LOCAL_IMAGES = Object.freeze(${JSON.stringify(local)});`,
    "",
  ].join("\n"),
);
console.log(`${local.length}/${Object.keys(REMOTE_IMAGES).length} images local.`);
